def set_font(run, size=12, bold=False, color=None):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.name = "仿宋"
    run.font.color.rgb = RGBColor(0, 0, 0) if color is None else color
    r = run._element
    rPr = r.get_or_add_rPr()
    rFonts = rPr.get_or_add_rFonts()
    rFonts.set(qn("w:eastAsia"), "仿宋")


def add_title(doc, text, size=22, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.space_after = Pt(6)
    run = p.add_run(text)
    set_font(run, size=size, bold=bold)
    return p


def add_heading1(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(3)
    run = p.add_run(text)
    set_font(run, size=14, bold=True)
    return p


def add_heading2(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Inches(0.2)
    p.paragraph_format.space_before = Pt(4)
    run = p.add_run(text)
    set_font(run, size=12, bold=True)
    return p


def add_body(doc, text, indent=0.4):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Pt(24)
    if indent:
        p.paragraph_format.left_indent = Inches(indent) if indent != 0.4 else Pt(0)
    run = p.add_run(text)
    set_font(run, size=12)
    return p


def add_cite(doc, text):
    """法条引用段落，带缩进"""
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Inches(0.3)
    p.paragraph_format.first_line_indent = Pt(0)
    run = p.add_run(text)
    set_font(run, size=11)
    run.font.color.rgb = RGBColor(0x33, 0x33, 0x33)
    return p


