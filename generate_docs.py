    section.page_height = Pt(842)
    section.left_margin = Inches(1.18)
    section.right_margin = Inches(1.18)
    section.top_margin = Inches(1.0)
    section.bottom_margin = Inches(1.0)

    for i, line in enumerate(content.strip().splitlines()):
        stripped = line.strip()
        if not stripped:
            doc.add_paragraph()
            continue

        # 主标题
        if i == 0 and "状" in stripped or "书" in stripped:
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            r = p.add_run(stripped)
            set_font(r, size=22, bold=True)
        # 一级条款标题（一、二、三、四、）
        elif stripped[:2] in ("一、", "二、", "三、", "四、", "五、", "六、"):
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(8)
            r = p.add_run(stripped)
            set_font(r, size=13, bold=True)
        # 二级条款标题（（一）（二）等）
        elif stripped[:3] in ("（一）", "（二）", "（三）", "（四）", "（五）", "（六）"):
            p = doc.add_paragraph()
            p.paragraph_format.first_line_indent = Pt(24)
            p.paragraph_format.space_before = Pt(4)
            r = p.add_run(stripped)
            set_font(r, size=12, bold=True)
        # 法条引用（以"《"开头或"根据"开头的引用块）
        elif stripped.startswith("《") or stripped.startswith("“"):
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Inches(0.25)
            p.paragraph_format.first_line_indent = Pt(0)
            r = p.add_run(stripped)
            set_font(r, size=11)
            r.font.color.rgb = RGBColor(0x33, 0x33, 0x99)
        # 风险评估行
        elif stripped.startswith("【风险"):
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Inches(0.25)
            r = p.add_run(stripped)
            set_font(r, size=11, bold=True)
            r.font.color.rgb = RGBColor(0xCC, 0x44, 0x00)
        # 普通正文
        else:
            p = doc.add_paragraph()
            p.paragraph_format.first_line_indent = Pt(24)
            r = p.add_run(stripped)
            set_font(r, size=12)

    buf = BytesIO()
    doc.save(buf)
    buf.seek(0)
    return buf


